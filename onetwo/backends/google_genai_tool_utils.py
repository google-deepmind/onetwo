"""Utilities for extracting and matching tool call details for Google GenAI SDK."""

from collections.abc import Sequence
from typing import Any, TypeAlias

from google.genai import types as genai_types
from onetwo.core import function_calling


FunctionCallDetail = function_calling.FunctionCallDetail
FunctionResponseDetail = function_calling.FunctionResponseDetail
ThoughtDetail = function_calling.ThoughtDetail
ToolCallDetail: TypeAlias = function_calling.ToolCallDetail


def dump_pydantic(val: Any) -> Any:
  """Unwraps Pydantic models (or dicts of Pydantic models) to JSON dicts.

  Args:
    val: Any object, dictionary, or Pydantic model to unwrap.

  Returns:
    JSON-serializable data structure with Pydantic models dumped to dicts.
  """
  if hasattr(val, 'model_dump'):
    return val.model_dump(mode='json')
  if isinstance(val, dict):
    return {
        k: v.model_dump(mode='json') if hasattr(v, 'model_dump') else v
        for k, v in val.items()
    }
  return val


def attach_function_response_to_tool_details(
    function_response: genai_types.FunctionResponse,
    current_turn_details: list[ToolCallDetail],
    accumulated_details: Sequence[ToolCallDetail] | None = None,
) -> None:
  """Matches a FunctionResponse to its preceding FunctionCall and attaches it.

  In automatic function calling (e.g. MCP tools), `function_response` parts
  appear in subsequent turns of AFC history. This function finds the
  corresponding `function_call` detail (searching backwards through
  `current_turn_details` and then `accumulated_details`), dumps any Pydantic
  model into a JSON-serializable dictionary, and stores it in the `'response'`
  field.

  If no matching function call is found, appends a standalone function_response
  record to `current_turn_details` so no data is lost.

  Args:
    function_response: The FunctionResponse object from the model response turn.
    current_turn_details: List of tool details from the current turn being
      extracted.
    accumulated_details: Optional list of tool details accumulated from earlier
      turns.
  """
  name = getattr(function_response, 'name', None)
  if not name or not isinstance(name, str):
    return

  resp_id = getattr(function_response, 'id', None)
  if not isinstance(resp_id, str):
    resp_id = None

  serialized_response = dump_pydantic(function_response.response)

  # Search backwards through current turn calls first, then past turns.
  for target_list in (current_turn_details, accumulated_details or []):
    for detail in reversed(target_list):
      if (
          not isinstance(detail, FunctionCallDetail)
          or detail.response is not None
      ):
        continue
      # 1. Primary: Match by explicit call ID when available.
      if resp_id and detail.id == resp_id:
        detail.response = serialized_response
        return
      # 2. Fallback: Sequential name match when ID is absent.
      if not resp_id and detail.name == name:
        detail.response = serialized_response
        return

  # 3. Safety fallback: If no matching function_call is found, append an
  # orphan record so no data is lost.
  current_turn_details.append(
      FunctionResponseDetail(name=name, response=serialized_response)
  )


def extract_tool_calls_from_parts(
    parts: Sequence[genai_types.Part] | None,
    existing_details: Sequence[ToolCallDetail] | None = None,
) -> tuple[int, list[ToolCallDetail]]:
  """Extracts tool call details and counts function calls from a list of parts.

  Note on 'thought' details vs 'llm.tokens.thoughts':
    - 'llm.tokens.thoughts' records the numeric count of thinking/reasoning
      tokens from usage_metadata.
    - 'thought' entries in tool_call_details capture the actual reasoning text
      (`part.text` when `part.thought=True`) generated by thinking-enabled
      models before or between tool call executions.

  Args:
    parts: A sequence of genai_types.Part objects.
    existing_details: Optional existing list of tool details to search when
      matching function response parts.

  Returns:
    A tuple containing:
      - The number of function calls.
      - A list of structured tool call details.
  """
  tool_call_count = 0
  tool_call_details: list[ToolCallDetail] = []
  if parts:
    for part in parts:
      if part.function_call and isinstance(
          (fc_name := getattr(part.function_call, 'name', None)), str
      ):
        tool_call_count += 1
        fc_id = getattr(part.function_call, 'id', None)
        detail = FunctionCallDetail(
            name=fc_name,
            args=part.function_call.args,
            id=fc_id if isinstance(fc_id, str) else None,
        )
        tool_call_details.append(detail)
      elif part.function_response and isinstance(
          getattr(part.function_response, 'name', None), str
      ):
        attach_function_response_to_tool_details(
            part.function_response,
            current_turn_details=tool_call_details,
            accumulated_details=existing_details,
        )
      elif getattr(part, 'thought', False) and isinstance(
          (thought_text := getattr(part, 'text', None)), str
      ):
        detail = ThoughtDetail(text=thought_text)
        tool_call_details.append(detail)
  return tool_call_count, tool_call_details

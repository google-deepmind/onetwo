"""Implementation of a Gemini Function Calling strategy using Agent framework.

This agent acts as the orchestrator for Gemini's native Function Calling 2.0
(FC2.0) protocol (see documentation:
https://ai.google.dev/gemini-api/docs/function-calling).

Adopting the "Agent" framework for the Gemini Function Calling implementation
means that:
* The full state of the strategy at each step is encapsulated in a
  serializable state object (GeminiFCState), which in this case is represented
  as a series of steps, each of which consists of some combination of thought,
  fn_calls (function/tool calls), fn_responses (tool responses), and answer.
* This ensures that in addition to running the full strategy end-to-end, we are
  also able to support stop/restart, stepwise execution, and composition of
  this strategy with other agent strategies such as BeamSearch, for pursuing
  multiple possible trajectories in parallel.
"""

import dataclasses
from typing import Any

from onetwo.agents import agents_base
from onetwo.core import content as content_lib
from onetwo.core import executing
from onetwo.core import tracing
from onetwo.stdlib.tool_use import llm_tool_use
from onetwo.stdlib.tool_use import python_tool_use


# Dataclass to represent a step in the Gemini Function Calling strategy.
@dataclasses.dataclass
class GeminiFCStep:
  """Represents a single step in the Gemini Function Calling execution.

  Attributes:
    thought: Optional text reasoning generated by the model.
    fn_calls: List of structured function calls requested by the model.
    fn_responses: List of structured responses from tool executions.
    answer: Final answer to the user, if no more tools are needed.
  """

  thought: str | None = None
  fn_calls: list[llm_tool_use.FunctionCall] = dataclasses.field(
      default_factory=list
  )
  fn_responses: list[Any] = dataclasses.field(default_factory=list)
  answer: str | None = None


# State consists of a monotonically increasing sequence of steps.
GeminiFCState = agents_base.UpdateListState[
    str | content_lib.ChunkList, GeminiFCStep
]


@dataclasses.dataclass
class GeminiFCAgent(
    agents_base.SingleSampleAgent[
        str | content_lib.ChunkList,  # _I (inputs)
        str,  # _O (outputs)
        GeminiFCState,  # _S (state)
        GeminiFCStep,  # _U (update)
        python_tool_use.PythonToolUseEnvironment,  # _E (environment)
    ]
):
  """Agent for Gemini Function Calling 2.0 strategy.

  This agent orchestrates the conversation loop by sending history and tool
  declarations to the model, receiving structured function calls, executing
  them, and returning structured responses.

  Attributes:
    tools: List of tools available to the agent.
    exemplars: Few-shot exemplars to include in the prompt history.
  """

  tools: list[llm_tool_use.Tool]
  exemplars: list[GeminiFCState] = dataclasses.field(default_factory=list)

  @executing.make_executable(copy_self=False, non_copied_args=['environment'])
  @tracing.trace('GeminiFCAgent._sample_single_next_step', skip=['environment'])
  async def _sample_single_next_step(
      self,
      *,
      state: GeminiFCState,
      environment: python_tool_use.PythonToolUseEnvironment | None = None,
  ) -> GeminiFCStep:
    """Runs one step of the strategy and returns a new resulting state.

    Overridden from base class (SingleSampleAgent).

    Args:
      state: Current state of the agent.
      environment: Environment in which to perform the operation.

    Returns:
      An incremental update to the agent state that would occur as a result of
      performing the given step.
    """
    raise NotImplementedError('Subclasses must implement this method.')

  @executing.make_executable(copy_self=False, non_copied_args=['environment'])
  async def initialize_state(
      self,
      inputs: str | content_lib.ChunkList,
      environment: python_tool_use.PythonToolUseEnvironment | None = None,
  ) -> GeminiFCState:
    """Returns a newly initialized state based on the input.

    Overridden from base class (Agent).

    Args:
      inputs: Input to the agent, representing the overall goal.
      environment: Environment in which to perform the operation.

    Returns:
      A GeminiFCState.
    """
    raise NotImplementedError('Subclasses must implement this method.')

  def extract_output(self, state: GeminiFCState) -> str | None:
    """Returns the output from the strategy if stopping at the given state.

    Args:
      state: The current execution state containing the history.

    Returns:
      The output from the strategy, or None if not finished.
    """
    raise NotImplementedError('Subclasses must implement this method.')
